#!/usr/bin/env bash

set -euo pipefail

SRC="$HOME/.ai/agents"
SRC_LOCAL="$HOME/.ai/agents.local"
DST="${1:-$HOME/.codex/agents}"
MARKER="# Generated by ~/.ai/scripts/sync-codex-agents.sh. Do not edit."

mkdir -p "$DST"

# Read a single "key: value" line from the source's YAML frontmatter.
frontmatter_value() {
  local key="$1" file="$2"
  awk -v key="$key" '
    NR == 1 && $0 == "---" { fm = 1; next }
    fm && $0 == "---" { exit }
    fm && $0 ~ "^" key ": " {
      sub("^" key ": *", "")
      print
      exit
    }
  ' "$file"
}

sync_agent() {
  local source="$1"
  local name target description
  name="$(basename "$source" .md)"
  target="$DST/$name.toml"

  # Escape for a TOML basic string.
  description="$(frontmatter_value "description" "$source")"
  case "$description" in
    ''|\"*|\'*|'>'*|'|'*)
      echo "Unsupported description in $source: use one plain unquoted line" >&2
      exit 1
      ;;
  esac
  description="${description//\\/\\\\}"
  description="${description//\"/\\\"}"

  # Codex-specific model/effort from frontmatter. Absent means: inherit
  # Codex's default model/effort.
  local codex_model codex_effort codex_sandbox
  codex_model="$(frontmatter_value "codex-model" "$source")"
  codex_effort="$(frontmatter_value "codex-effort" "$source")"
  codex_sandbox="$(frontmatter_value "codex-sandbox" "$source")"

  # Strip YAML frontmatter from shared Markdown agent.
  body="$(
    awk '
      BEGIN { frontmatter = 0; done = 0 }

      NR == 1 && $0 == "---" {
        frontmatter = 1
        next
      }

      frontmatter && $0 == "---" {
        frontmatter = 0
        done = 1
        next
      }

      !frontmatter && done {
        print
      }
    ' "$source"
  )"

  if [[ "$body" == *"'''"* ]]; then
    echo "Agent body contains ''' and cannot be written as TOML: $source" >&2
    exit 1
  fi

  local backup tmp
  if [[ -L "$target" ]]; then
    rm "$target"
  elif [[ -f "$target" && "$(head -n 1 "$target")" != "$MARKER" ]]; then
    backup="${target}.backup"
    if [[ -e "$backup" || -L "$backup" ]]; then
      backup="${target}.backup.$(date +%Y%m%d%H%M%S)"
    fi
    echo "Backing up: $target -> $backup"
    mv "$target" "$backup"
  fi

  tmp="$(mktemp "$DST/.sync.XXXXXX")"
  if ! {
    echo "$MARKER"
    echo "name = \"$name\""
    echo "description = \"$description\""
    [[ -n "$codex_model" ]] && echo "model = \"$codex_model\""
    [[ -n "$codex_effort" ]] && echo "model_reasoning_effort = \"$codex_effort\""
    echo "sandbox_mode = \"${codex_sandbox:-read-only}\""
    echo
    # Literal string: backslashes in the body stay as written.
    echo "developer_instructions = '''"
    echo "$body"
    echo "'''"
  } > "$tmp" || ! mv "$tmp" "$target"; then
    rm -f "$tmp"
    exit 1
  fi

  echo "Synced: $target"
}

for source in "$SRC"/*.md "$SRC_LOCAL"/*.md; do
  [[ -f "$source" ]] || continue
  sync_agent "$source"
done

for target in "$DST"/*.toml; do
  [[ -f "$target" && ! -L "$target" ]] || continue
  [[ "$(head -n 1 "$target")" == "$MARKER" ]] || continue
  name="$(basename "$target" .toml).md"
  [[ ! -f "$SRC/$name" && ! -f "$SRC_LOCAL/$name" ]] || continue

  rm "$target"
  echo "Pruned: $target"
done

echo "Codex agents synced."
