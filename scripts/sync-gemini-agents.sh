#!/usr/bin/env bash

set -euo pipefail

SRC="$HOME/.ai/agents"
SRC_LOCAL="$HOME/.ai/agents.local"
DST="${1:-$HOME/.gemini/config/agents}"
MARKER="<!-- Generated by ~/.ai/scripts/sync-gemini-agents.sh. Do not edit. -->"

mkdir -p "$DST"

has_frontmatter() {
  awk '
    NR == 1 && $0 == "---" { fm = 1; next }
    fm && $0 == "---" { closed = 1; exit }
    END { exit(closed ? 0 : 1) }
  ' "$1"
}

frontmatter_value() {
  local key="$1" file="$2"
  awk -v key="$key" '
    NR == 1 && $0 == "---" { fm = 1; next }
    fm && $0 == "---" { exit }
    fm && $0 ~ "^" key ":[[:space:]]*" {
      sub("^" key ":[[:space:]]*", "")
      print
      exit
    }
  ' "$file"
}

sync_agent() {
  local source="$1"
  local name target_dir target description gemini_model backup tmp
  name="$(basename "$source" .md)"
  target_dir="$DST/$name"
  target="$target_dir/agent.md"

  if ! has_frontmatter "$source"; then
    echo "Missing frontmatter in $source" >&2
    exit 1
  fi

  description="$(frontmatter_value "description" "$source")"
  case "$description" in
    ''|\"*|\'*|'>'*|'|'*)
      echo "Unsupported description in $source: use one plain unquoted line" >&2
      exit 1
      ;;
  esac

  gemini_model="$(frontmatter_value "gemini-model" "$source")"
  case "$gemini_model" in
    ''|inherit|flash_lite|flash|pro) ;;
    *)
      echo "Unsupported gemini-model in $source: $gemini_model (use inherit, flash_lite, flash, or pro)" >&2
      exit 1
      ;;
  esac

  mkdir -p "$target_dir"

  if [[ -L "$target" ]]; then
    rm "$target"
  elif [[ -f "$target" && "$(tail -n 1 "$target")" != "$MARKER" ]]; then
    backup="${target}.backup"
    if [[ -e "$backup" || -L "$backup" ]]; then
      backup="${target}.backup.$(date +%Y%m%d%H%M%S)"
    fi
    echo "Backing up: $target -> $backup"
    mv "$target" "$backup"
  fi

  tmp="$(mktemp "$target_dir/.sync.XXXXXX")"
  if ! {
    awk -v fallback_name="$name" '
      function has_token(list, tok,    n, i, arr) {
        n = split(list, arr, /,[[:space:]]*/)
        for (i = 1; i <= n; i++) {
          if (arr[i] == tok) return 1
        }
        return 0
      }
      function add_tool(t) {
        if (!seen[t]++) mapped = (mapped ? mapped ", " : "") t
      }
      NR == 1 && $0 == "---" { fm = 1; next }
      fm && $0 == "---" {
        fm = 0
        done = 1
        if (agent_name == "") agent_name = fallback_name
        gsub(/\\/, "\\\\", desc)
        gsub(/"/, "\\\"", desc)

        if (tools != "") {
          n = split(tools, arr, /,[[:space:]]*/)
          for (i = 1; i <= n; i++) {
            t = arr[i]
            if (t == "Read" || t == "Glob" || t == "Grep") add_tool("read_file")
            else if (t == "Edit" || t == "MultiEdit") add_tool("edit_file")
            else if (t == "Write") add_tool("write_file")
            else if (t == "Bash") { add_tool("run_command"); add_tool("manage_task") }
            else if (t == "WebSearch" || t == "WebFetch") add_tool("search_web")
          }
        } else {
          add_tool("read_file")
          if (!has_token(disallowed, "Edit") && !has_token(disallowed, "MultiEdit")) add_tool("edit_file")
          if (!has_token(disallowed, "Write")) add_tool("write_file")
          add_tool("run_command")
          add_tool("manage_task")
          add_tool("search_web")
        }

        print "---"
        print "name: " agent_name
        print "description: \"" desc "\""
        print "subagent: true"
        print "mainAgent: true"
        if (gmodel != "") print "model: " gmodel
        print "tools: [" mapped "]"
        print "---"
        next
      }
      fm {
        if ($0 ~ /^name:[[:space:]]*/) { sub(/^name:[[:space:]]*/, ""); agent_name = $0 }
        else if ($0 ~ /^description:[[:space:]]*/) { sub(/^description:[[:space:]]*/, ""); desc = $0 }
        else if ($0 ~ /^tools:[[:space:]]*/) { sub(/^tools:[[:space:]]*/, ""); tools = $0 }
        else if ($0 ~ /^disallowedTools:[[:space:]]*/) { sub(/^disallowedTools:[[:space:]]*/, ""); disallowed = $0 }
        else if ($0 ~ /^gemini-model:[[:space:]]*/) { sub(/^gemini-model:[[:space:]]*/, ""); gmodel = $0 }
        next
      }
      done { print }
    ' "$source" && printf '%s\n' "$MARKER"
  } > "$tmp" || ! mv "$tmp" "$target"; then
    rm -f "$tmp"
    exit 1
  fi

  echo "Synced: $target"
}

for source in "$SRC"/*.md "$SRC_LOCAL"/*.md; do
  [[ -f "$source" ]] || continue
  sync_agent "$source"
done

for target in "$DST"/*/agent.md; do
  [[ -f "$target" && ! -L "$target" ]] || continue
  [[ "$(tail -n 1 "$target")" == "$MARKER" ]] || continue
  target_dir="$(dirname "$target")"
  name="$(basename "$target_dir")"
  [[ ! -f "$SRC/$name.md" && ! -f "$SRC_LOCAL/$name.md" ]] || continue

  rm "$target"
  rmdir "$target_dir" 2>/dev/null || true
  echo "Pruned: $target"
done

for target in "$DST"/*.md; do
  [[ -f "$target" && ! -L "$target" ]] || continue
  [[ "$(tail -n 1 "$target")" == "$MARKER" ]] || continue

  rm "$target"
  echo "Pruned legacy: $target"
done

echo "Gemini agents synced."
