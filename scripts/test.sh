#!/usr/bin/env bash

set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TEST_HOME="$(mktemp -d)"
trap 'rm -rf "$TEST_HOME"' EXIT

mkdir -p "$TEST_HOME/.ai"
cp -R "$REPO/GLOBAL.md" "$REPO/bootstrap.sh" "$REPO/agents" "$REPO/skills" "$REPO/scripts" "$TEST_HOME/.ai/"

CHECKS=0

pass() {
  CHECKS=$((CHECKS + 1))
  printf '✓ %s\n' "$1"
}

die() {
  printf '✗ %s\n' "$1" >&2
  exit 1
}

assert_link() {
  local target="$1" expected="$2"

  [[ -L "$target" ]] || die "Not a symlink: $target"
  [[ "$(readlink "$target")" == "$expected" ]] || die "$target does not point to $expected"
}

echo "==> Dry run changes nothing"

env HOME="$TEST_HOME" DRY_RUN=1 "$TEST_HOME/.ai/bootstrap.sh" >/dev/null
for dir in .claude .codex .gemini .copilot .agents .agent; do
  [[ ! -e "$TEST_HOME/$dir" ]] || die "Dry run created $dir"
done
pass "dry run wrote nothing"

echo "==> Bootstrap creates links and keeps a backup"

mkdir -p "$TEST_HOME/.codex"
echo "old instructions" > "$TEST_HOME/.codex/AGENTS.md"
env HOME="$TEST_HOME" "$TEST_HOME/.ai/bootstrap.sh" >/dev/null

assert_link "$TEST_HOME/.claude/CLAUDE.md" "$TEST_HOME/.ai/GLOBAL.md"
assert_link "$TEST_HOME/.codex/AGENTS.md" "$TEST_HOME/.ai/GLOBAL.md"
assert_link "$TEST_HOME/.gemini/GEMINI.md" "$TEST_HOME/.ai/GLOBAL.md"
assert_link "$TEST_HOME/.copilot/copilot-instructions.md" "$TEST_HOME/.ai/GLOBAL.md"
pass "global context links"

[[ "$(cat "$TEST_HOME/.codex/AGENTS.md.backup")" == "old instructions" ]] || die "Backup missing"
pass "existing file backed up"

for skill in "$TEST_HOME"/.ai/skills/*/; do
  name="$(basename "$skill")"
  for dir in .claude/skills .gemini/config/skills .agents/skills .agent/skills; do
    assert_link "$TEST_HOME/$dir/x-$name" "$TEST_HOME/.ai/skills/$name"
  done
done
pass "skill links"

for agent in "$TEST_HOME"/.ai/agents/*.md; do
  name="$(basename "$agent")"
  assert_link "$TEST_HOME/.claude/agents/$name" "$agent"
  [[ -s "$TEST_HOME/.gemini/config/agents/$name" && ! -L "$TEST_HOME/.gemini/config/agents/$name" ]] || die "Missing Gemini agent: $name"
  [[ -s "$TEST_HOME/.codex/agents/${name%.md}.toml" ]] || die "Missing Codex agent: ${name%.md}.toml"
done
pass "agent links, Gemini agents, and Codex agents"

echo "==> Bootstrap is safe to run twice"

env HOME="$TEST_HOME" "$TEST_HOME/.ai/bootstrap.sh" >/dev/null
assert_link "$TEST_HOME/.claude/CLAUDE.md" "$TEST_HOME/.ai/GLOBAL.md"
[[ "$(cat "$TEST_HOME/.codex/AGENTS.md.backup")" == "old instructions" ]] || die "Backup changed"
pass "second run"

echo "==> Bootstrap prunes leftovers and keeps foreign files"

ln -s "$TEST_HOME/.ai/skills/gone" "$TEST_HOME/.claude/skills/x-gone"
ln -s "$TEST_HOME/.ai/agents/gone.md" "$TEST_HOME/.claude/agents/gone.md"
ln -s "$TEST_HOME/elsewhere" "$TEST_HOME/.claude/skills/foreign"
printf '%s\n' "<!-- Generated by ~/.ai/scripts/sync-gemini-agents.sh. Do not edit. -->" > "$TEST_HOME/.gemini/config/agents/gone.md"
printf '%s\n' "# Generated by ~/.ai/scripts/sync-codex-agents.sh. Do not edit." > "$TEST_HOME/.codex/agents/gone.toml"
echo "mine" > "$TEST_HOME/.gemini/config/agents/mine.md"
echo 'name = "mine"' > "$TEST_HOME/.codex/agents/mine.toml"

env HOME="$TEST_HOME" "$TEST_HOME/.ai/bootstrap.sh" >/dev/null

[[ ! -L "$TEST_HOME/.claude/skills/x-gone" ]] || die "Dangling skill link not pruned"
[[ ! -L "$TEST_HOME/.claude/agents/gone.md" ]] || die "Dangling Claude agent link not pruned"
[[ ! -e "$TEST_HOME/.gemini/config/agents/gone.md" ]] || die "Orphan Gemini agent not pruned"
[[ ! -e "$TEST_HOME/.codex/agents/gone.toml" ]] || die "Orphan Codex agent not pruned"
[[ -L "$TEST_HOME/.claude/skills/foreign" ]] || die "Foreign dangling link was removed"
[[ -f "$TEST_HOME/.gemini/config/agents/mine.md" ]] || die "Foreign Gemini agent was removed"
[[ -f "$TEST_HOME/.codex/agents/mine.toml" ]] || die "Foreign Codex agent was removed"
pass "leftovers pruned and foreign files kept"

echo "==> Codex sync rejects unsupported frontmatter"

mkdir -p "$TEST_HOME/bad-home/.ai/agents"
cat > "$TEST_HOME/bad-home/.ai/agents/bad.md" <<'EOF'
---
name: bad
description: "quoted"
---
Body
EOF
if env HOME="$TEST_HOME/bad-home" "$TEST_HOME/.ai/scripts/sync-codex-agents.sh" >/dev/null 2>&1; then
  die "sync-codex-agents.sh accepted quoted description"
fi
pass "unsupported frontmatter rejected"

echo "==> Doctor reports no failures"

env HOME="$TEST_HOME" PATH="/usr/bin:/bin" "$TEST_HOME/.ai/scripts/doctor.sh" > "$TEST_HOME/doctor.log" ||
  { cat "$TEST_HOME/doctor.log"; die "doctor.sh failed"; }
grep -q '^Failures: 0$' "$TEST_HOME/doctor.log" || die "doctor.sh reported failures"
pass "doctor"

echo "==> Doctor compares generated agents by content"

touch -t 200001010000 \
  "$TEST_HOME/.gemini/config/agents/builder.md" \
  "$TEST_HOME/.codex/agents/builder.toml"
env HOME="$TEST_HOME" PATH="/usr/bin:/bin" "$TEST_HOME/.ai/scripts/doctor.sh" > "$TEST_HOME/doctor-mtime.log" ||
  { cat "$TEST_HOME/doctor-mtime.log"; die "doctor.sh failed after mtime change"; }
if grep -Eq '^! .*builder\.(md|toml)' "$TEST_HOME/doctor-mtime.log"; then
  cat "$TEST_HOME/doctor-mtime.log"
  die "doctor.sh warned on unchanged content with old mtime"
fi
pass "old mtime does not warn"

printf '\n# edited\n' >> "$TEST_HOME/.gemini/config/agents/builder.md"
printf '\n# edited\n' >> "$TEST_HOME/.codex/agents/builder.toml"
env HOME="$TEST_HOME" PATH="/usr/bin:/bin" "$TEST_HOME/.ai/scripts/doctor.sh" > "$TEST_HOME/doctor-edited.log" ||
  { cat "$TEST_HOME/doctor-edited.log"; die "doctor.sh failed after content edit"; }
grep -q '^! Gemini agent out of date:' "$TEST_HOME/doctor-edited.log" ||
  { cat "$TEST_HOME/doctor-edited.log"; die "doctor.sh missed edited Gemini agent"; }
grep -q '^! Codex agent out of date:' "$TEST_HOME/doctor-edited.log" ||
  { cat "$TEST_HOME/doctor-edited.log"; die "doctor.sh missed edited Codex agent"; }
pass "edited content warns for Gemini and Codex"

printf '\nAll %d checks passed.\n' "$CHECKS"
