#!/usr/bin/env bash
# Sourced by the ~/.ai scripts. Never run directly.
# shellcheck disable=SC2034

AI_HOME="$HOME/.ai"
AGENT_SOURCE_DIRS=("$AI_HOME/agents" "$AI_HOME/agents.local")
SKILL_SOURCE_DIRS=("$AI_HOME/skills" "$AI_HOME/skills.local")
GLOBAL_CONTEXT_TARGETS=("$HOME/.claude/CLAUDE.md" "$HOME/.codex/AGENTS.md" "$HOME/.gemini/GEMINI.md")
SKILL_LINK_DIRS=("$HOME/.claude/skills" "$HOME/.gemini/config/skills" "$HOME/.agents/skills")
CLAUDE_AGENT_DIR="$HOME/.claude/agents"
CODEX_AGENT_DIR="$HOME/.codex/agents"
GEMINI_AGENT_DIR="$HOME/.gemini/config/agents"

# Created by old bootstrap versions. Only uninstall.sh removes them.
LEGACY_GLOBAL_CONTEXT_TARGETS=("$HOME/.copilot/copilot-instructions.md")
LEGACY_SKILL_LINK_DIRS=("$HOME/.agent/skills")

CODEX_MARKER="# Generated by ~/.ai/scripts/sync-codex-agents.sh. Do not edit."
GEMINI_MARKER="<!-- Generated by ~/.ai/scripts/sync-gemini-agents.sh. Do not edit. -->"

PLAYWRIGHT_CONFIG="$HOME/.playwright/cli.config.json"

DRY_RUN="${DRY_RUN:-0}"
BACKUP_SUFFIX=".backup"

run() {
  if [[ "$DRY_RUN" == "1" ]]; then
    printf '[dry-run]'
    printf ' %q' "$@"
    printf '\n'
  else
    "$@"
  fi
}

owned_link() {
  [[ -L "$1" && "$(readlink "$1")" == "$AI_HOME"/* ]]
}

is_codex_generated() {
  [[ -f "$1" && ! -L "$1" && "$(head -n 1 "$1")" == "$CODEX_MARKER" ]]
}

is_gemini_generated() {
  [[ -f "$1" && ! -L "$1" && "$(tail -n 1 "$1")" == "$GEMINI_MARKER" ]]
}

# Print the path of the winning source for an agent file name, or return 1.
agent_source() {
  local path="" dir
  for dir in "${AGENT_SOURCE_DIRS[@]}"; do
    [[ -f "$dir/$1" ]] && path="$dir/$1"
  done
  [[ -n "$path" ]] && printf '%s\n' "$path"
}

# Print the path of the winning source for a skill name, or return 1.
skill_source() {
  local path="" dir
  for dir in "${SKILL_SOURCE_DIRS[@]}"; do
    [[ -d "$dir/$1" ]] && path="$dir/$1"
  done
  [[ -n "$path" ]] && printf '%s\n' "$path"
}

# Print the winning source path for every agent name, sorted by name.
agent_sources() {
  local dir file
  for dir in "${AGENT_SOURCE_DIRS[@]}"; do
    for file in "$dir"/*.md; do
      [[ -f "$file" ]] && basename "$file"
    done
  done | sort -u | while IFS= read -r name; do
    agent_source "$name"
  done
}

# Print the winning source path for every skill name, sorted by name.
skill_sources() {
  local dir skill
  for dir in "${SKILL_SOURCE_DIRS[@]}"; do
    for skill in "$dir"/*; do
      [[ -d "$skill" ]] && basename "$skill"
    done
  done | sort -u | while IFS= read -r name; do
    skill_source "$name"
  done
}

has_frontmatter() {
  awk '
    NR == 1 && $0 == "---" { fm = 1; next }
    fm && $0 == "---" { closed = 1; exit }
    END { exit(closed ? 0 : 1) }
  ' "$1"
}

# Escape for a double-quoted YAML or TOML string.
escape_double_quoted() {
  local value="$1"

  value="${value//\\/\\\\}"
  value="${value//\"/\\\"}"
  printf '%s\n' "$value"
}

playwright_config_content() {
  local pw_dir="${TMPDIR:-/tmp}"

  pw_dir="${pw_dir%/}"
  printf '{\n  "outputDir": "%s/playwright-cli"\n}\n' "$pw_dir"
}

# Read a single "key: value" line from the source's YAML frontmatter.
frontmatter_value() {
  local key="$1" file="$2"
  awk -v key="$key" '
    NR == 1 && $0 == "---" { fm = 1; next }
    fm && $0 == "---" { exit }
    fm && $0 ~ "^" key ":[[:space:]]*" {
      sub("^" key ":[[:space:]]*", "")
      print
      exit
    }
  ' "$file"
}

# Print everything after the closing "---" of the frontmatter.
frontmatter_body() {
  awk '
    NR == 1 && $0 == "---" { fm = 1; next }
    fm && $0 == "---" { fm = 0; done = 1; next }
    done { print }
  ' "$1"
}

plain_description() {
  local description

  if ! has_frontmatter "$1"; then
    echo "Missing frontmatter in $1" >&2
    return 1
  fi

  description="$(frontmatter_value "description" "$1")"

  case "$description" in
    ''|\"*|\'*|'>'*|'|'*)
      echo "Unsupported description in $1: use one plain unquoted line" >&2
      return 1
      ;;
  esac

  printf '%s\n' "$description"
}

next_backup_path() {
  local backup="${1}$BACKUP_SUFFIX"

  if [[ -e "$backup" || -L "$backup" ]]; then
    backup="$backup.$(date +%Y%m%d%H%M%S)"
  fi

  printf '%s\n' "$backup"
}

# Make room for a generated file: drop a symlink, back up a file we did not generate.
prepare_generated_target() {
  local target="$1" is_generated="$2" backup

  if [[ -L "$target" ]]; then
    rm "$target"
  elif [[ -f "$target" ]] && ! "$is_generated" "$target"; then
    backup="$(next_backup_path "$target")"
    echo "Backing up: $target -> $backup"
    mv "$target" "$backup"
  fi
}
