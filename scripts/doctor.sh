#!/usr/bin/env bash

set -uo pipefail

AI_HOME="$HOME/.ai"

FAILURES=0
WARNINGS=0

ok() {
  printf '✓ %s\n' "$1"
}

warn() {
  printf '! %s\n' "$1"
  WARNINGS=$((WARNINGS + 1))
}

fail() {
  printf '✗ %s\n' "$1"
  FAILURES=$((FAILURES + 1))
}

section() {
  printf '\n==> %s\n' "$1"
}

resolve_path() {
  local path="$1"

  if command -v realpath >/dev/null 2>&1; then
    realpath "$path" 2>/dev/null
  elif command -v python3 >/dev/null 2>&1; then
    python3 -c 'import os, sys; print(os.path.realpath(sys.argv[1]))' "$path" 2>/dev/null
  else
    return 1
  fi
}

check_link() {
  local target="$1"
  local expected="$2"

  if [[ ! -e "$target" && ! -L "$target" ]]; then
    fail "Missing: $target"
    return
  fi

  if [[ ! -L "$target" ]]; then
    warn "Not symlink: $target"
    return
  fi

  if [[ ! -e "$target" ]]; then
    fail "Broken symlink: $target"
    return
  fi

  local resolved_target
  local resolved_expected

  resolved_target="$(resolve_path "$target" || true)"
  resolved_expected="$(resolve_path "$expected" || true)"

  if [[ -z "$resolved_target" || -z "$resolved_expected" ]]; then
    warn "Could not resolve symlink: $target"
    return
  fi

  if [[ "$resolved_target" == "$resolved_expected" ]]; then
    ok "$target -> $expected"
  else
    fail "$target points to $resolved_target, expected $resolved_expected"
  fi
}

check_dangling() {
  local dir="$1"
  local link

  [[ -d "$dir" ]] || return 0

  for link in "$dir"/*; do
    [[ -L "$link" && ! -e "$link" ]] || continue
    [[ "$(readlink "$link")" == "$AI_HOME"/* ]] || continue

    fail "Dangling link: $link (run bootstrap.sh)"
  done
}

section "Shared configuration"

for file in \
  "$AI_HOME/GLOBAL.md" \
  "$AI_HOME/bootstrap.sh"
do
  if [[ -f "$file" ]]; then
    ok "$file"
  else
    fail "Missing: $file"
  fi
done

section "Global context links"

check_link "$HOME/.claude/CLAUDE.md" "$AI_HOME/GLOBAL.md"
check_link "$HOME/.codex/AGENTS.md" "$AI_HOME/GLOBAL.md"
check_link "$HOME/.gemini/GEMINI.md" "$AI_HOME/GLOBAL.md"
check_link "$HOME/.copilot/copilot-instructions.md" "$AI_HOME/GLOBAL.md"

section "Shared skills"

check_skill() {
  local skill="$1"
  local name
  name="$(basename "$skill")"

  if [[ ! -f "$skill/SKILL.md" ]]; then
    fail "$name missing SKILL.md"
    return
  fi

  ok "$name"

  check_link "$HOME/.claude/skills/x-$name" "$skill"
  check_link "$HOME/.gemini/config/skills/x-$name" "$skill"
  check_link "$HOME/.agents/skills/x-$name" "$skill"
  check_link "$HOME/.agent/skills/x-$name" "$skill"
}

for skill in "$AI_HOME"/skills/*; do
  [[ -d "$skill" ]] || continue
  [[ ! -d "$AI_HOME/skills.local/$(basename "$skill")" ]] || continue
  check_skill "$skill"
done

for skill in "$AI_HOME"/skills.local/*; do
  [[ -d "$skill" ]] || continue
  check_skill "$skill"
done

check_dangling "$HOME/.claude/skills"
check_dangling "$HOME/.gemini/config/skills"
check_dangling "$HOME/.agents/skills"
check_dangling "$HOME/.agent/skills"

section "Shared agents"

expected_dir="$(mktemp -d)"
trap 'rm -rf "$expected_dir"' EXIT

gemini_synced=1
if ! "$AI_HOME/scripts/sync-gemini-agents.sh" "$expected_dir/gemini" >/dev/null 2>&1; then
  fail "sync-gemini-agents.sh failed; Gemini agents cannot be compared"
  gemini_synced=0
fi

codex_synced=1
if ! "$AI_HOME/scripts/sync-codex-agents.sh" "$expected_dir/codex" >/dev/null 2>&1; then
  fail "sync-codex-agents.sh failed; Codex agents cannot be compared"
  codex_synced=0
fi

check_agent() {
  local agent="$1"
  local name agent_id gemini_agent codex_agent
  name="$(basename "$agent")"
  agent_id="${name%.md}"
  gemini_agent="$HOME/.gemini/config/agents/$agent_id/agent.md"
  codex_agent="$HOME/.codex/agents/$agent_id.toml"

  ok "$name"

  check_link "$HOME/.claude/agents/$name" "$agent"

  if [[ -L "$gemini_agent" ]]; then
    fail "Gemini agent is a raw symlink: $gemini_agent"
  elif [[ ! -f "$gemini_agent" ]]; then
    warn "Gemini agent not synced: $gemini_agent"
  elif (( gemini_synced )) && ! cmp -s "$expected_dir/gemini/$agent_id/agent.md" "$gemini_agent"; then
    warn "Gemini agent out of date: $gemini_agent (run sync-gemini-agents.sh)"
  elif (( gemini_synced )); then
    ok "$gemini_agent"
  fi

  if [[ ! -f "$codex_agent" ]]; then
    warn "Codex agent not synced: $codex_agent"
  elif (( codex_synced )) && ! cmp -s "$expected_dir/codex/$agent_id.toml" "$codex_agent"; then
    warn "Codex agent out of date: $codex_agent (run sync-codex-agents.sh)"
  elif (( codex_synced )); then
    ok "$codex_agent"
  fi
}

for agent in "$AI_HOME"/agents/*.md; do
  [[ -f "$agent" ]] || continue
  [[ ! -f "$AI_HOME/agents.local/$(basename "$agent")" ]] || continue
  check_agent "$agent"
done

for agent in "$AI_HOME"/agents.local/*.md; do
  [[ -f "$agent" ]] || continue
  check_agent "$agent"
done

check_dangling "$HOME/.claude/agents"

gemini_marker="<!-- Generated by ~/.ai/scripts/sync-gemini-agents.sh. Do not edit. -->"
for gemini_agent in "$HOME"/.gemini/config/agents/*/agent.md; do
  [[ -f "$gemini_agent" && ! -L "$gemini_agent" ]] || continue
  [[ "$(tail -n 1 "$gemini_agent")" == "$gemini_marker" ]] || continue
  agent_id="$(basename "$(dirname "$gemini_agent")")"
  [[ ! -f "$AI_HOME/agents/$agent_id.md" && ! -f "$AI_HOME/agents.local/$agent_id.md" ]] || continue

  fail "Orphan Gemini agent: $gemini_agent (run sync-gemini-agents.sh)"
done

for gemini_agent in "$HOME"/.gemini/config/agents/*.md; do
  [[ -f "$gemini_agent" && ! -L "$gemini_agent" ]] || continue
  [[ "$(tail -n 1 "$gemini_agent")" == "$gemini_marker" ]] || continue

  fail "Legacy Gemini agent: $gemini_agent (run sync-gemini-agents.sh)"
done

codex_marker="# Generated by ~/.ai/scripts/sync-codex-agents.sh. Do not edit."
for codex_agent in "$HOME"/.codex/agents/*.toml; do
  [[ -f "$codex_agent" && ! -L "$codex_agent" ]] || continue
  [[ "$(head -n 1 "$codex_agent")" == "$codex_marker" ]] || continue
  name="$(basename "$codex_agent" .toml).md"
  [[ ! -f "$AI_HOME/agents/$name" && ! -f "$AI_HOME/agents.local/$name" ]] || continue

  fail "Orphan Codex agent: $codex_agent (run sync-codex-agents.sh)"
done

section "Scripts"

for script in "$AI_HOME"/scripts/*.sh "$AI_HOME/bootstrap.sh"; do
  [[ -f "$script" ]] || continue

  name="$(basename "$script")"

  if [[ -x "$script" ]]; then
    ok "$name executable"
  else
    fail "$name not executable"
  fi

  if bash -n "$script" >/dev/null 2>&1; then
    ok "$name syntax"
  else
    fail "$name syntax error"
  fi
done

if command -v shellcheck >/dev/null 2>&1; then
  section "ShellCheck"

  for script in "$AI_HOME"/scripts/*.sh "$AI_HOME/bootstrap.sh"; do
    [[ -f "$script" ]] || continue

    name="$(basename "$script")"

    if shellcheck "$script" >/dev/null 2>&1; then
      ok "$name"
    else
      warn "$name has ShellCheck findings"
    fi
  done
fi

section "JSON configs"

if command -v jq >/dev/null 2>&1; then
  json_files=(
    "$HOME/.claude/settings.json"
    "$HOME/.gemini/antigravity-cli/settings.json"
    "$HOME/.gemini/config/hooks.json"
  )

  for file in "${json_files[@]}"; do
    [[ -f "$file" ]] || continue

    if jq empty "$file" >/dev/null 2>&1; then
      ok "$file"
    else
      fail "Invalid JSON: $file"
    fi
  done

  for file in "$HOME"/.copilot/hooks/*.json; do
    [[ -f "$file" ]] || continue

    if jq empty "$file" >/dev/null 2>&1; then
      ok "$file"
    else
      fail "Invalid JSON: $file"
    fi
  done
else
  warn "jq not installed; JSON validation skipped"
fi

section "Codex TOML"

if command -v python3 >/dev/null 2>&1 &&
   python3 -c 'import tomllib' >/dev/null 2>&1; then

  toml_files=("$HOME/.codex/config.toml")

  for file in "$HOME"/.codex/agents/*.toml; do
    [[ -f "$file" ]] && toml_files+=("$file")
  done

  for file in "${toml_files[@]}"; do
    [[ -f "$file" ]] || continue

    if python3 - "$file" <<'PY' >/dev/null 2>&1
import sys
import tomllib

with open(sys.argv[1], "rb") as f:
    tomllib.load(f)
PY
    then
      ok "$file"
    else
      fail "Invalid TOML: $file"
    fi
  done
else
  warn "Python tomllib unavailable; TOML validation skipped"
fi

section "Tools"

show_version() {
  local binary="$1"
  shift

  if ! command -v "$binary" >/dev/null 2>&1; then
    warn "$binary not installed"
    return
  fi

  local output
  output="$("$@" 2>&1 || true)"
  output="${output%%$'\n'*}"

  if [[ -n "$output" ]]; then
    ok "$binary: $output"
  else
    warn "$binary installed but version unavailable"
  fi
}

show_version claude claude --version
show_version codex codex --version
show_version agy agy --version
show_version rtk rtk --version
show_version ctx7 ctx7 --version
show_version playwright-cli playwright-cli --version

section "Claude integrations"

if command -v claude >/dev/null 2>&1; then
  plugin_output="$(claude plugin list 2>/dev/null || true)"

  if grep -q 'ponytail' <<<"$plugin_output"; then
    ok "Ponytail detected"
  else
    warn "Ponytail not detected"
  fi

  if grep -q 'typescript-lsp' <<<"$plugin_output"; then
    ok "TypeScript LSP detected"
  else
    warn "TypeScript LSP not detected"
  fi
fi

section "RTK"

if command -v rtk >/dev/null 2>&1; then
  rtk_output="$(rtk init --show 2>/dev/null || true)"

  if grep -q '\[ok\] Hook:' <<<"$rtk_output"; then
    ok "RTK Claude hook configured"
  else
    warn "RTK Claude hook not detected"
  fi

  gain_output="$(rtk gain 2>/dev/null || true)"

  if [[ -n "$gain_output" ]]; then
    saved_line="$(grep 'Tokens saved:' <<<"$gain_output" | head -n 1 || true)"

    if [[ -n "$saved_line" ]]; then
      ok "$saved_line"
    fi
  fi
else
  warn "rtk not installed"
fi

section "Bootstrap"

if [[ -x "$AI_HOME/bootstrap.sh" ]]; then
  ok "bootstrap.sh present and executable"

  if grep -q 'DRY_RUN' "$AI_HOME/bootstrap.sh"; then
    ok "bootstrap.sh declares DRY_RUN support"
  else
    warn "bootstrap.sh has no DRY_RUN support"
  fi

  printf '  Run manually when needed:\n'
  printf '  DRY_RUN=1 %s/bootstrap.sh\n' "$AI_HOME"
else
  fail "bootstrap.sh not executable"
fi

printf '\n==> Summary\n'
printf 'Failures: %d\n' "$FAILURES"
printf 'Warnings: %d\n' "$WARNINGS"

if (( FAILURES > 0 )); then
  exit 1
fi

exit 0
