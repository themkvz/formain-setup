#!/usr/bin/env bash

set -euo pipefail

AI_HOME="$HOME/.ai"
DRY_RUN="${DRY_RUN:-0}"
LEFTOVERS=""

run() {
  if [[ "$DRY_RUN" == "1" ]]; then
    printf '[dry-run]'
    printf ' %q' "$@"
    printf '\n'
  else
    "$@"
  fi
}

ai_link() {
  [[ -L "$1" && "$(readlink "$1")" == "$AI_HOME"/* ]]
}

# Remove an item, then move its original back from P.backup.
remove_item() {
  local path="$1" backup

  echo "Removed: $path"
  run rm "$path"

  if [[ -e "$path.backup" || -L "$path.backup" ]]; then
    run mv "$path.backup" "$path"
    echo "Restored: $path"
  fi

  for backup in "$path".backup.*; do
    [[ -e "$backup" || -L "$backup" ]] || continue
    LEFTOVERS="$LEFTOVERS$backup"$'\n'
  done
}

echo "==> Global context links"

for file in \
  "$HOME/.claude/CLAUDE.md" \
  "$HOME/.codex/AGENTS.md" \
  "$HOME/.gemini/GEMINI.md" \
  "$HOME/.copilot/copilot-instructions.md"
do
  if ai_link "$file"; then remove_item "$file"; fi
done

echo
echo "==> Shared links"

for dir in \
  "$HOME/.claude/skills" \
  "$HOME/.claude/agents" \
  "$HOME/.gemini/config/skills" \
  "$HOME/.agents/skills" \
  "$HOME/.agent/skills"
do
  for link in "$dir"/*; do
    if ai_link "$link"; then remove_item "$link"; fi
  done
done

echo
echo "==> Generated agents"

codex_marker="# Generated by ~/.ai/scripts/sync-codex-agents.sh. Do not edit."
for agent in "$HOME"/.codex/agents/*.toml; do
  [[ -f "$agent" && ! -L "$agent" && "$(head -n 1 "$agent")" == "$codex_marker" ]] || continue
  remove_item "$agent"
done

gemini_marker="<!-- Generated by ~/.ai/scripts/sync-gemini-agents.sh. Do not edit. -->"
for agent in "$HOME"/.gemini/config/agents/*/agent.md; do
  [[ -f "$agent" && ! -L "$agent" && "$(tail -n 1 "$agent")" == "$gemini_marker" ]] || continue
  remove_item "$agent"
  run rmdir "$(dirname "$agent")" 2>/dev/null || true
done

for dir in \
  "$HOME/.claude/skills" \
  "$HOME/.claude/agents" \
  "$HOME/.gemini/config/skills" \
  "$HOME/.gemini/config/agents" \
  "$HOME/.codex/agents" \
  "$HOME/.agents/skills" \
  "$HOME/.agents" \
  "$HOME/.agent/skills" \
  "$HOME/.agent"
do
  [[ -d "$dir" && ! -L "$dir" && -z "$(ls -A "$dir")" ]] || continue
  run rmdir "$dir"
  echo "Removed empty folder: $dir"
done

echo
if [[ -n "$LEFTOVERS" ]]; then
  echo "Leftover timestamped backups (review manually):"
  printf '%s' "$LEFTOVERS"
  echo
fi

if [[ "$DRY_RUN" == "1" ]]; then
  echo "AI uninstall dry run complete. Nothing changed."
else
  echo "AI uninstall complete."
fi
